def emotions_treker(user_message):
    user_message = user_message.lower() #строчные буквы
    
    joy_count = 0
    sadness_count = 0
    fear_count = 0
    anger_count = 0
    #считаем добрые слова
    for word in joy_list:
        if word in user_message:
            joy_count += 1
    #считаем грустные слова
    for word in sadness_list:
        if word in user_message:
            sadness_count += 1
    #считаем страшные слова        
    for word in fear_list:
        if word in user_message:
            fear_count += 1
    #считаем злые слова
    for word in anger_list:
        if word in user_message:
            anger_count += 1
            
    result_emotions = {
        'РАДОСТЬ' : joy_count,
        'ГРУСТЬ' : sadness_count,
        'СТРАХ' : fear_count,
        'ЗЛОСТЬ' : anger_count,
    } 
    
    if joy_count==0 and sadness_count==0 and fear_count==0 and anger_count==0:
        return "NO_EMOTION", 1
    else: 
        win_emotion = max(result_emotions, key = result_emotions.get)
        win_count = result_emotions[win_emotion]
        statist = win_count/sum(result_emotions.values())
        return win_emotion, statist
     

